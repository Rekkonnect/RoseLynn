#!/usr/bin/dotnet run
#:project ../../src/RoseLynn/RoseLynn.Core.csproj
#:project ../../src/RoseLynn.CSharp/RoseLynn.CSharp.csproj
#:package Garyon
#:package Microsoft.CodeAnalysis.CSharp

using System.Collections.Immutable;
using Garyon.Functions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using RoseLynn.CSharp;

var solutionDirectory = WorkspaceHelpers.GetThisSolutionRoot()
    ?? throw new InvalidOperationException("Could not locate the solution root.");

var srcDirectory = new DirectoryInfo(Path.Combine(solutionDirectory.FullName, "src"));
if (!srcDirectory.Exists)
    throw new DirectoryNotFoundException($"src/ not found under {solutionDirectory.FullName}");

var projectDirectories = srcDirectory
    .GetDirectories()
    .Where(d => d.GetFiles("*.csproj").Length > 0)
    .OrderBy(d => d.Name)
    .ToList();

Console.WriteLine($"Scanning {projectDirectories.Count} project(s) under {srcDirectory.FullName}");
Console.WriteLine();

var allUndocumented = new List<(string Project, string SymbolName)>();

var parseOptions = new CSharpParseOptions(
    languageVersion: LanguageVersion.Default,
    documentationMode: DocumentationMode.Diagnose);

var metadataReferences = GetTrustedPlatformAssemblyReferences();

foreach (var projectDirectory in projectDirectories)
{
    var sourceFiles = projectDirectory
        .GetFiles("*.cs", SearchOption.AllDirectories)
        .Where(f => !IsInObjDirectory(f))
        .ToArray();

    if (sourceFiles.Length == 0)
        continue;

    var syntaxTrees = sourceFiles
        .Select(f => (File: f, Text: File.ReadAllText(f.FullName)))
        .Where(x => !IsAutoGenerated(x.Text))
        .Select(x => CSharpSyntaxTree.ParseText(x.Text, parseOptions, x.File.FullName))
        .ToArray();

    var compilation = CSharpCompilation.Create(
        projectDirectory.Name,
        syntaxTrees,
        metadataReferences,
        new CSharpCompilationOptions(
            OutputKind.DynamicallyLinkedLibrary,
            nullableContextOptions: NullableContextOptions.Enable));

    foreach (var tree in syntaxTrees)
    {
        var semanticModel = compilation.GetSemanticModel(tree);
        var walker = new UndocumentedDeclarationWalker(semanticModel, compilation);
        walker.Visit(tree.GetRoot());

        foreach (var name in walker.UndocumentedMembers)
            allUndocumented.Add((projectDirectory.Name, name));
    }
}

if (allUndocumented.Count == 0)
{
    Console.WriteLine("All public members are documented.");
    return 0;
}

Console.WriteLine($"Found {allUndocumented.Count} undocumented public member(s):");
Console.WriteLine();

foreach (var group in allUndocumented.GroupBy(x => x.Project).OrderBy(g => g.Key))
{
    Console.WriteLine($"[{group.Key}]");
    foreach (var (_, name) in group.OrderBy(x => x.SymbolName))
        Console.WriteLine($"  {name}");
    Console.WriteLine();
}

return 0;

static bool IsInObjDirectory(FileInfo file) =>
    file.FullName.Contains(
        $"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}",
        StringComparison.OrdinalIgnoreCase);

static bool IsAutoGenerated(string text)
{
    var firstLine = text.AsSpan();
    var nl = firstLine.IndexOfAny('\r', '\n');
    if (nl >= 0)
        firstLine = firstLine[..nl];
    firstLine = firstLine.TrimStart();
    return firstLine.StartsWith("// <auto-generated>", StringComparison.OrdinalIgnoreCase);
}

static ImmutableArray<MetadataReference> GetTrustedPlatformAssemblyReferences()
{
    var paths = AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") as string;
    if (paths is null)
        return [];

    return [.. paths
        .Split(Path.PathSeparator)
        .Select(p => (MetadataReference)MetadataReference.CreateFromFile(p))];
}

/// <summary>
/// Walks a syntax tree to discover only syntactically-declared members, then uses the
/// semantic model to check whether each has XML documentation.  This avoids false
/// positives from compiler-synthesised symbols (record properties, Deconstruct,
/// primary-constructor parameters, etc.) that have no explicit declaration in source.
/// </summary>
sealed class UndocumentedDeclarationWalker(SemanticModel semanticModel, Compilation compilation)
    : CSharpSyntaxWalker
{
    private readonly List<string> _undocumentedMembers = [];

    public IReadOnlyList<string> UndocumentedMembers => _undocumentedMembers;

    // ── Type declarations ────────────────────────────────────────────────────

    public override void VisitClassDeclaration(ClassDeclarationSyntax node)
    {
        CheckTypeMember(node);
        base.VisitClassDeclaration(node);
    }

    public override void VisitStructDeclaration(StructDeclarationSyntax node)
    {
        CheckTypeMember(node);
        base.VisitStructDeclaration(node);
    }

    public override void VisitInterfaceDeclaration(InterfaceDeclarationSyntax node)
    {
        CheckTypeMember(node);
        base.VisitInterfaceDeclaration(node);
    }

    public override void VisitRecordDeclaration(RecordDeclarationSyntax node)
    {
        CheckTypeMember(node);
        base.VisitRecordDeclaration(node);
    }

    public override void VisitEnumDeclaration(EnumDeclarationSyntax node)
    {
        CheckTypeMember(node);
        base.VisitEnumDeclaration(node);
    }

    public override void VisitDelegateDeclaration(DelegateDeclarationSyntax node)
    {
        CheckTypeMember(node);
        base.VisitDelegateDeclaration(node);
    }

    // ── Member declarations ──────────────────────────────────────────────────

    public override void VisitMethodDeclaration(MethodDeclarationSyntax node)
    {
        CheckSymbolMember(node);
        base.VisitMethodDeclaration(node);
    }

    public override void VisitConstructorDeclaration(ConstructorDeclarationSyntax node)
    {
        CheckSymbolMember(node);
        base.VisitConstructorDeclaration(node);
    }

    public override void VisitOperatorDeclaration(OperatorDeclarationSyntax node)
    {
        CheckSymbolMember(node);
        base.VisitOperatorDeclaration(node);
    }

    public override void VisitConversionOperatorDeclaration(ConversionOperatorDeclarationSyntax node)
    {
        CheckSymbolMember(node);
        base.VisitConversionOperatorDeclaration(node);
    }

    public override void VisitPropertyDeclaration(PropertyDeclarationSyntax node)
    {
        CheckSymbolMember(node);
        base.VisitPropertyDeclaration(node);
    }

    public override void VisitIndexerDeclaration(IndexerDeclarationSyntax node)
    {
        CheckSymbolMember(node);
        base.VisitIndexerDeclaration(node);
    }

    public override void VisitEventDeclaration(EventDeclarationSyntax node)
    {
        CheckSymbolMember(node);
        base.VisitEventDeclaration(node);
    }

    public override void VisitEnumMemberDeclaration(EnumMemberDeclarationSyntax node)
    {
        CheckSymbolMember(node);
        base.VisitEnumMemberDeclaration(node);
    }

    // Fields and event-fields declare multiple symbols per declaration node.

    public override void VisitFieldDeclaration(FieldDeclarationSyntax node)
    {
        foreach (var declarator in node.Declaration.Variables)
        {
            var symbol = semanticModel.GetDeclaredSymbol(declarator);
            if (symbol is IFieldSymbol field && IsVisible(field) && IsInAccessibleContainer(field))
                CheckAndRecord(field);
        }
        base.VisitFieldDeclaration(node);
    }

    public override void VisitEventFieldDeclaration(EventFieldDeclarationSyntax node)
    {
        foreach (var declarator in node.Declaration.Variables)
        {
            var symbol = semanticModel.GetDeclaredSymbol(declarator);
            if (symbol is IEventSymbol evt && IsVisible(evt) && IsInAccessibleContainer(evt))
                CheckAndRecord(evt);
        }
        base.VisitEventFieldDeclaration(node);
    }

    // ── Helpers ──────────────────────────────────────────────────────────────

    private void CheckTypeMember(MemberDeclarationSyntax node)
    {
        var symbol = semanticModel.GetDeclaredSymbol(node) as INamedTypeSymbol;
        if (symbol is not null && IsVisible(symbol) && !IsExtensionBlockType(symbol) && IsInAccessibleContainer(symbol))
            CheckAndRecord(symbol);
    }

    private void CheckSymbolMember(MemberDeclarationSyntax node)
    {
        var symbol = semanticModel.GetDeclaredSymbol(node);
        if (symbol is not null && IsVisible(symbol) && IsInAccessibleContainer(symbol))
            CheckAndRecord(symbol);
    }

    private static bool IsVisible(ISymbol symbol) =>
        symbol.DeclaredAccessibility
            is Accessibility.Public
            or Accessibility.Protected
            or Accessibility.ProtectedOrInternal;

    private static bool IsInAccessibleContainer(ISymbol symbol)
    {
        var container = symbol.ContainingType;
        while (container is not null)
        {
            if (!IsVisible(container))
                return false;
            container = container.ContainingType;
        }
        return true;
    }

    // Extension block types are compiler-synthesised containers; their names are
    // wrapped in angle brackets by the compiler (e.g. "<Extension$Bar>").
    private static bool IsExtensionBlockType(INamedTypeSymbol symbol)
    {
        var name = symbol.Name;
        return name.Length > 2 && name[0] == '<' && name[^1] == '>';
    }

    private void CheckAndRecord(ISymbol symbol)
    {
        var xml = symbol.GetDocumentationCommentXml();
        if (!string.IsNullOrWhiteSpace(xml))
            return;

        _undocumentedMembers.Add(FormatSymbol(symbol));
    }

    private string FormatSymbol(ISymbol symbol)
    {
        if (symbol is INamedTypeSymbol)
            return $"type {SymbolNameHelpers.FullyQualifiedString(symbol, compilation)}";

        var containerFqn = SymbolNameHelpers.FullyQualifiedString(symbol.ContainingType, compilation);
        var kind = GetMemberKind(symbol);
        var memberDisplay = symbol.ToDisplayString(MemberSignatureFormat);
        return $"in {containerFqn} {kind} {memberDisplay}";
    }

    private static string GetMemberKind(ISymbol symbol) => symbol switch
    {
        IMethodSymbol { MethodKind: MethodKind.Constructor } => "constructor",
        IMethodSymbol { MethodKind: MethodKind.UserDefinedOperator } => "operator",
        IMethodSymbol { MethodKind: MethodKind.Conversion } => "conversion",
        IMethodSymbol => "method",
        IPropertySymbol { IsIndexer: true } => "indexer",
        IPropertySymbol => "property",
        IFieldSymbol => "field",
        IEventSymbol => "event",
        _ => "member",
    };

    private static readonly SymbolDisplayFormat MemberSignatureFormat = new(
        memberOptions:
            SymbolDisplayMemberOptions.IncludeParameters |
            SymbolDisplayMemberOptions.IncludeRef,
        parameterOptions:
            SymbolDisplayParameterOptions.IncludeType |
            SymbolDisplayParameterOptions.IncludeName |
            SymbolDisplayParameterOptions.IncludeParamsRefOut,
        genericsOptions:
            SymbolDisplayGenericsOptions.IncludeTypeParameters,
        miscellaneousOptions:
            SymbolDisplayMiscellaneousOptions.UseSpecialTypes);
}
