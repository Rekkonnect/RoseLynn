async Task WriteFiles(
    SignatureViewFileList list,
    CancellationToken cancellationToken)
{
    foreach (var file in list.Files)
    {
        await WriteFile(file, cancellationToken);
    }
}

async Task WriteFile(
    SignatureViewFile file,
    CancellationToken cancellationToken)
{
    await signatureViewFileDirectory
        .File(file.FileName)
        .WriteAllTextAsync(file.Content, cancellationToken);
}

static CancellationTokenSource CreateCancelKeyTokenSource()
{
    var tokenSource = new CancellationTokenSource();
    Console.CancelKeyPress += (_, e) =>
    {
        e.Cancel = true;
        tokenSource.Cancel();
    };
    return tokenSource;
}

sealed class CompilationRunner : BaseCSharpCompilationEffort
{
    public async Task<SignatureViewFileList> CreateFiles(CancellationToken cancellationToken)
    {
        var compilation = await CreateCompilation(cancellationToken);
        if (compilation is null)
        {
            throw new InvalidOperationException(
                "The compilation was not created successfully");
        }
        compilation = compilation.WithNullableContextOptions(NullableContextOptions.Enable);
        var specialTypes = GetUsableSpecialTypes();
        var files = specialTypes
            .Select(specialType => CreateFile(compilation, specialType))
            .WhereNotNull()
            .ToList();
        return new(files);
    }

    private static ImmutableArray<SpecialType> GetUsableSpecialTypes()
    {
        return Enum.GetValues<SpecialType>()
            .Except([
                SpecialType.None,
                SpecialType.Count,
            ])
            .ToImmutableArray();
    }

    private SignatureViewFile? CreateFile(
        Compilation compilation,
        SpecialType specialType)
    {
        var type = compilation.GetSpecialType(specialType);
        if (type is null)
        {
            return null;
        }

        var signatureView = type.ToSymbolSignatureView(compilation);
        return WriteFile(specialType, signatureView);
    }

    private static SignatureViewFile WriteFile(
        SpecialType specialType,
        INamedTypeSymbolSignatureView signatureView)
    {
        var fileName = GeneratedFileHelpers.SpecialTypeFileName(specialType);
        var content = WriteContent(specialType, signatureView);
        return new(fileName, content);
    }

    private static string WriteContent(
        SpecialType specialType,
        INamedTypeSymbolSignatureView signatureView)
    {
        var builder = new SignatureViewFileBuilder(specialType, signatureView);
        return builder.BuildFile();
    }
}

sealed class SignatureViewFileBuilder(
    SpecialType specialType,
    ISymbolSignatureView signatureView)
    : CSharpSourceFileBuilder<CSharpCodeWriter>
{
    protected override CSharpCodeWriter CreateCodeBuilder() => new();

    protected override string? GetHeader()
    {
        return $$"""
            // <auto-generated>
            //     This file has been auto-generated by
            //     special-type-signature-view-generator.cs
            //     for Roslyn version {{typeof(SpecialType).Assembly.GetName().Version}}
            // </auto-generated>

            using Microsoft.CodeAnalysis;

            namespace RoseLynn.SignatureViews;

            #nullable enable

            """;
    }

    protected override string? GetFooter() => null;

    protected override void BuildContent()
    {
        var writer = MainContentWriter;

        writer.AppendLine(
            "public static partial class WellKnownSymbolSignatureViews");
        using (writer.EnterBracketBlock())
        {
            WriteSpecialSymbol();
        }
    }

    // Many ASSUMPTION comments will follow, for the sake of not over-engineering
    // an already over-engineered part of this project
    private void WriteSpecialSymbol()
    {
        var writer = MainContentWriter;

        var specialTypeName = specialType.ToString();
        var fieldName = specialTypeName;
        var methodName = $"Create{specialTypeName}";
        writer.AppendLine($"public static readonly INamedTypeSymbolSignatureView {fieldName}");
        writer.AppendLine($"    = {methodName}();");
        writer.AppendLine();
        writer.AppendLine($"private static NamedTypeSymbolSignatureView {methodName}()");

        using (writer.EnterBracketBlock())
        {
            WriteCreationMethodBody(writer);
        }
    }

    private void WriteCreationMethodBody(CSharpCodeWriter writer)
    {
        writer.Append("return ");
        AppendObjectCreation(signatureView, writer);
        writer.AppendLine(";");
    }

    private void AppendPropertyAssignment<T>(
        PropertyInfo propertyInfo,
        T value,
        CSharpCodeWriter writer)
    {
        writer.Append($"{propertyInfo.Name} = ");
        AppendValue(value, writer);
        writer.AppendLine(",");
    }

    private void AppendValue<T>(T value, CSharpCodeWriter writer)
    {
        if (value is null)
        {
            AppendNullLiteral(writer);
            return;
        }

        var valueType = value.GetType();
        var typeCode = valueType.GetTypeCode();
        if (typeCode is TypeCode.Boolean)
        {
            AppendBoolean(value, writer);
            return;
        }

        if (typeCode is TypeCode.String)
        {
            AppendString(value, writer);
            return;
        }

        if (valueType.IsEnum)
        {
            AppendEnum(value, writer);
            return;
        }

        if (IsNumberSupportingLiteral(typeCode))
        {
            AppendNumber(value, writer);
            return;
        }

        // ASSUMPTION: any enumerable type supports collection expressions,
        // and if it fails it's a hint that the proper API must be placed
        // for collection expressions
        var supportsCollectionExpression = valueType.GetInterfaces()
            .Any(s => s.IsGenericVariantOf(typeof(IEnumerable<>)));

        if (supportsCollectionExpression)
        {
            AppendCollectionExpression(value, writer);
            return;
        }

#pragma warning disable CS8714 // The type cannot be used as type parameter in the generic type or method. Nullability of type argument doesn't match 'notnull' constraint.
        AppendObjectCreation(value!, writer);
#pragma warning restore CS8714 // The type cannot be used as type parameter in the generic type or method. Nullability of type argument doesn't match 'notnull' constraint.
    }

    private void AppendNullLiteral(CSharpCodeWriter writer)
    {
        writer.Append("null");
    }

    private void AppendBoolean<T>(T value, CSharpCodeWriter writer)
    {
        // ASSUMPTION: only bool values will enter this method
        var text = value is true ? "true" : "false";
        writer.Append(text);
    }

    private void AppendString<T>(T value, CSharpCodeWriter writer)
    {
        // ASSUMPTION: strings will not need escaping
        var s = value as string;
        if (s is null)
        {
            return;
        }

        writer.Append($"\"{s}\"");
    }

    private void AppendNumber<T>(T value, CSharpCodeWriter writer)
    {
        var literal = value!.ToString()!;
        writer.Append(literal);
    }

    private void AppendEnum<T>(T value, CSharpCodeWriter writer)
    {
        // ASSUMPTION: full qualification will be redundant
        var type = value!.GetType();
        var typeName = type.Name;
        writer.Append($"{typeName}.{value.ToString()}");
    }

    private void AppendCollectionExpression<T>(T value, CSharpCodeWriter writer)
    {
        var enumerable = value as IEnumerable;
        var values = enumerable?.Cast<T>().ToImmutableArray() ?? [];
        if (values is [])
        {
            writer.Append("[]");
            return;
        }

        writer.AppendLine("[");

        using (writer.EnterNestingBlock())
        {
            using (writer.EnterNestingBlock())
            {
                foreach (var inner in values)
                {
                    AppendValue(inner, writer);
                    writer.AppendLine(",");
                }
            }

            writer.Append("]");
        }
    }

    private void AppendObjectCreation<T>(
        T value,
        CSharpCodeWriter writer)
        where T : notnull
    {
        var type = value.GetType();

        writer.AppendLine($"new {type.Name}");
        writer.AppendLine("{");
        using (writer.EnterNestingBlock())
        {
            var properties = type.GetProperties()
                .Where(s => s.CanWrite)
                .ToList();

            foreach (var property in properties)
            {
                var propertyValue = property.GetValue(value);
                AppendPropertyAssignment(property, propertyValue, writer);
            }
        }
        writer.Append("}");
    }

    private static bool IsNumberSupportingLiteral(TypeCode typeCode)
    {
        return typeCode
            is TypeCode.Byte
            or TypeCode.Int16
            or TypeCode.Int32
            or TypeCode.Int64
            or TypeCode.SByte
            or TypeCode.UInt16
            or TypeCode.UInt32
            or TypeCode.UInt64
            or TypeCode.Single
            or TypeCode.Double
            or TypeCode.Decimal
            ;
    }
}

sealed record SignatureViewFileList(IReadOnlyList<SignatureViewFile> Files);

