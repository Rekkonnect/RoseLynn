static class GeneratedFileHelpers
{
    public const string FilesPrefix = "WellKnownSymbolSignatureViews";

    public static string SpecialTypeFileName(SpecialType specialType)
    {
        return $"{FilesPrefix}.{specialType}.cs";
    }
}
